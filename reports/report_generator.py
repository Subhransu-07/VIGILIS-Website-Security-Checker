
import io
from datetime import datetime


def _fmt_date(iso_string: str) -> str:
    try:
        dt = datetime.fromisoformat(iso_string)
        return dt.strftime("%d %b %Y, %H:%M UTC")
    except (ValueError, TypeError):
        return iso_string or "Unknown"


def generate_txt(result: dict) -> bytes:
    lines = []
    lines.append("VIGILIS -- WEBSITE SECURITY ASSESSMENT REPORT")
    lines.append("=" * 50)
    lines.append(f"Website: {result['hostname']}")
    lines.append(f"Scan Date: {_fmt_date(result['scanned_at'])}")
    lines.append("")

    score = result["score"]
    lines.append(f"Overall Score: {score['total']} / {score['max']}")
    lines.append(f"Risk Rating: {score['rating']}")
    lines.append("")
    lines.append("SCORE BREAKDOWN")
    lines.append("-" * 50)
    for item in score["breakdown"]:
        lines.append(
            f"[{item['points_awarded']:>2}/{item['points_possible']:>2}] {item['label']} -- {item['reason']}"
        )
    lines.append("")

    https_ev = result["evidence"].get("https", {})
    lines.append("HTTPS VERIFICATION")
    lines.append("-" * 50)
    lines.append(f"HTTPS Enabled: {'Yes' if https_ev.get('https_available') else 'No'}")
    if https_ev.get("https_available") and https_ev.get("certificate_trusted") is not None:
        lines.append(f"Certificate Trusted: {'Yes' if https_ev.get('certificate_trusted') else 'No'}")
    lines.append(f"HTTP Available: {'Yes' if https_ev.get('http_available') else 'No'}")
    lines.append(f"HTTP redirects to HTTPS: {'Yes' if https_ev.get('http_redirects_to_https') else 'No'}")
    lines.append("")

    ssl_ev = result["evidence"].get("ssl", {})
    lines.append("SSL CERTIFICATE")
    lines.append("-" * 50)
    if ssl_ev.get("certificate_found"):
        lines.append(f"Issuer: {ssl_ev.get('issuer')}")
        lines.append(f"Valid From: {ssl_ev.get('valid_from')}")
        lines.append(f"Expires On: {ssl_ev.get('valid_until')}")
        lines.append(f"Days Remaining: {ssl_ev.get('days_remaining')}")
        lines.append(f"Status: {'Expired' if ssl_ev.get('is_expired') else 'Valid'}")
        if "trust_verified" in ssl_ev and ssl_ev.get("trust_verified") is not None:
            lines.append(f"Trusted by Browsers: {'Yes' if ssl_ev.get('trust_verified') else 'No'}")
        if ssl_ev.get("is_self_signed"):
            lines.append("Note: This certificate is self-signed.")
        elif ssl_ev.get("trust_verified") is False and ssl_ev.get("verification_error"):
            lines.append(f"Verification Note: {ssl_ev['verification_error']}")
    else:
        lines.append("No certificate could be retrieved.")
        if ssl_ev.get("error"):
            lines.append(f"Detail: {ssl_ev['error']}")
    lines.append("")

    lines.append("SECURITY HEADERS")
    lines.append("-" * 50)
    if result["evidence"].get("headers", {}).get("error"):
        lines.append(f"Note: {result['evidence']['headers']['error']}")
    headers = result["evidence"].get("headers", {}).get("headers", {})
    for key, info in headers.items():
        status = "Present" if info.get("present") else "Missing"
        lines.append(f"{info.get('header_name'):<28} {status}")
    lines.append("")

    lines.append("RECOMMENDATIONS")
    lines.append("-" * 50)
    for rec in result["recommendations"]:
        lines.append(f"* [{rec['severity']}] {rec['finding']}")
        lines.append(f"    Risk: {rec['risk']}")
        lines.append(f"    Recommendation: {rec['recommendation']}")
        lines.append("")

    lines.append("=" * 50)
    lines.append("Generated by VIGILIS -- Professional Website Security Assessment Platform")

    return "\n".join(lines).encode("utf-8")


def generate_html(result: dict) -> bytes:
    score = result["score"]
    https_ev = result["evidence"].get("https", {})
    ssl_ev = result["evidence"].get("ssl", {})
    headers = result["evidence"].get("headers", {}).get("headers", {})

    def yn(value):
        return "Yes" if value else "No"

    breakdown_rows = "".join(
        f"<tr><td>{item['label']}</td><td>{item['points_awarded']}/{item['points_possible']}</td>"
        f"<td>{item['reason']}</td></tr>"
        for item in score["breakdown"]
    )
    header_rows = "".join(
        f"<tr><td>{info.get('header_name')}</td>"
        f"<td class=\"{'ok' if info.get('present') else 'missing'}\">"
        f"{'Present' if info.get('present') else 'Missing'}</td></tr>"
        for info in headers.values()
    )
    rec_items = "".join(
        f"<li><strong>[{rec['severity']}] {rec['finding']}</strong><br>"
        f"Risk: {rec['risk']}<br>Recommendation: {rec['recommendation']}</li>"
        for rec in result["recommendations"]
    )

    trust_row = ""
    if "trust_verified" in ssl_ev and ssl_ev.get("trust_verified") is not None:
        trust_row = f"<tr><td>Trusted by Browsers</td><td>{yn(ssl_ev.get('trust_verified'))}</td></tr>"

    trust_note = ""
    if ssl_ev.get("is_self_signed"):
        trust_note = "<tr><td>Note</td><td>This certificate is self-signed.</td></tr>"
    elif ssl_ev.get("trust_verified") is False and ssl_ev.get("verification_error"):
        trust_note = f"<tr><td>Verification Note</td><td>{ssl_ev['verification_error']}</td></tr>"

