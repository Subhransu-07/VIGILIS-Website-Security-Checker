def generate_pdf(result: dict) -> bytes:
    """
    Generate a PDF report using reportlab. Falls back gracefully by
    raising ImportError if reportlab is unavailable -- the caller
    decides how to handle that (e.g. offer TXT/HTML instead).
    """
    from reportlab.lib.pagesizes import A4
    from reportlab.lib import colors
    from reportlab.lib.units import mm
    from reportlab.platypus import (
        SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle
    )
    from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle

    buffer = io.BytesIO()
    doc = SimpleDocTemplate(buffer, pagesize=A4, topMargin=20 * mm, bottomMargin=20 * mm)
    styles = getSampleStyleSheet()
    title_style = ParagraphStyle("VigilisTitle", parent=styles["Title"], textColor=colors.HexColor("#6D5DF6"))
    heading_style = ParagraphStyle("VigilisHeading", parent=styles["Heading2"], textColor=colors.HexColor("#3B82F6"))
    body_style = styles["BodyText"]

    ssl_ev = result["evidence"].get("ssl", {})
    https_ev = result["evidence"].get("https", {})

    story = [
        Paragraph("VIGILIS", title_style),
        Paragraph("Professional Website Security Assessment Report", body_style),
        Spacer(1, 12),
        Paragraph(f"<b>Website:</b> {result['hostname']}", body_style),
        Paragraph(f"<b>Scan Date:</b> {_fmt_date(result['scanned_at'])}", body_style),
        Spacer(1, 12),
        Paragraph(f"<b>Overall Score:</b> {result['score']['total']} / {result['score']['max']}", body_style),
        Paragraph(f"<b>Risk Rating:</b> {result['score']['rating']}", body_style),
        Spacer(1, 16),
        Paragraph("Score Breakdown", heading_style),
    ]

    breakdown_data = [["Category", "Points", "Reason"]]
    for item in result["score"]["breakdown"]:
        breakdown_data.append([
            item["label"],
            f"{item['points_awarded']}/{item['points_possible']}",
            item["reason"],
        ])
    breakdown_table = Table(breakdown_data, colWidths=[110, 50, 300])
    breakdown_table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#171B2D")),
        ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#2B3552")),
        ("FONTSIZE", (0, 0), (-1, -1), 8),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
    ]))
    story.append(breakdown_table)
    story.append(Spacer(1, 16))

    story.append(Paragraph("SSL Certificate", heading_style))
    if ssl_ev.get("certificate_found"):
        story.append(Paragraph(f"Issuer: {ssl_ev.get('issuer') or 'Unknown'}", body_style))
        story.append(Paragraph(f"Valid From: {ssl_ev.get('valid_from')}", body_style))
        story.append(Paragraph(f"Expires On: {ssl_ev.get('valid_until')}", body_style))
        status = "Expired" if ssl_ev.get("is_expired") else "Valid"
        story.append(Paragraph(f"Status: {status}", body_style))
        if "trust_verified" in ssl_ev and ssl_ev.get("trust_verified") is not None:
            trusted = "Yes" if ssl_ev.get("trust_verified") else "No"
            story.append(Paragraph(f"Trusted by Browsers: {trusted}", body_style))
        if ssl_ev.get("is_self_signed"):
            story.append(Paragraph("Note: This certificate is self-signed.", body_style))
        elif ssl_ev.get("trust_verified") is False and ssl_ev.get("verification_error"):
            story.append(Paragraph(f"Verification Note: {ssl_ev['verification_error']}", body_style))
    else:
        story.append(Paragraph(ssl_ev.get("error") or "No certificate could be retrieved.", body_style))
    story.append(Spacer(1, 16))

    story.append(Paragraph("Security Headers", heading_style))
    if result["evidence"].get("headers", {}).get("error"):
        story.append(Paragraph(result["evidence"]["headers"]["error"], body_style))
    headers = result["evidence"].get("headers", {}).get("headers", {})
    header_data = [["Header", "Status"]]
    for info in headers.values():
        header_data.append([info.get("header_name"), "Present" if info.get("present") else "Missing"])
    header_table = Table(header_data, colWidths=[250, 100])
    header_table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#171B2D")),
        ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#2B3552")),
        ("FONTSIZE", (0, 0), (-1, -1), 9),
    ]))
    story.append(header_table)
    story.append(Spacer(1, 16))

    story.append(Paragraph("Recommendations", heading_style))
    for rec in result["recommendations"]:
        story.append(Paragraph(f"<b>[{rec['severity']}] {rec['finding']}</b>", body_style))
        story.append(Paragraph(f"Risk: {rec['risk']}", body_style))
        story.append(Paragraph(f"Recommendation: {rec['recommendation']}", body_style))
        story.append(Spacer(1, 8))

    doc.build(story)
    return buffer.getvalue()
